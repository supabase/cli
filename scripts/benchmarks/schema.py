#!/usr/bin/env python3
"""Run one isolated declarative-schema benchmark sample against a Supabase CLI."""

from __future__ import annotations

import argparse
import json
import os
import platform
import resource
import shutil
import signal
import subprocess
import sys
import tempfile
import time
import uuid
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parent
FIXTURES = ROOT / "fixtures-schema"
TIMEOUT_SECONDS = 900
EXTENSIONS_SQL = (FIXTURES / "extensions.sql").read_text(encoding="utf-8")
SEED_SQL = (FIXTURES / "seed.sql").read_text(encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cli", required=True, type=Path)
    parser.add_argument("--implementation", required=True, choices=("new", "legacy"))
    parser.add_argument("--runtime", required=True, choices=("native", "docker"))
    parser.add_argument("--sample", required=True, type=int)
    parser.add_argument("--output", required=True, type=Path)
    return parser.parse_args()


def baseline_sql(table_count: int) -> str:
    tables = [
        """CREATE TABLE public.bench_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payload text NOT NULL
);"""
    ]
    tables.extend(
        f"CREATE TABLE public.bench_{index:03d} (id bigint PRIMARY KEY, label text NOT NULL);"
        for index in range(table_count)
    )
    return "\n\n".join(tables) + "\n"


def write_schema(project: Path, sql: str) -> None:
    schema_dir = project / "supabase" / "schemas"
    schema_dir.mkdir(parents=True, exist_ok=True)
    (schema_dir / "public.sql").write_text(sql, encoding="utf-8")
    extensions = schema_dir / "cluster" / "extensions.sql"
    extensions.parent.mkdir(parents=True, exist_ok=True)
    extensions.write_text(EXTENSIONS_SQL, encoding="utf-8")


def create_project(project: Path, implementation: str, table_count: int) -> None:
    project_id = f"bench_{uuid.uuid4().hex[:12]}"
    supabase = project / "supabase"
    migrations = supabase / "migrations"
    migrations.mkdir(parents=True, exist_ok=True)
    schema = baseline_sql(table_count)
    write_schema(project, schema)
    (migrations / "20260924000000_baseline.sql").write_text(
        EXTENSIONS_SQL + "\n" + schema, encoding="utf-8"
    )
    (supabase / "seed.sql").write_text(SEED_SQL, encoding="utf-8")
    config = [
        f'project_id = "{project_id}"',
        "",
        "[api]",
        "enabled = false",
        "",
        "[db]",
        "major_version = 17",
        "port = 54322",
        "shadow_port = 54321",
        "",
        "[db.seed]",
        'sql_paths = ["./seed.sql"]',
        "",
    ]
    if implementation == "new":
        config.extend(
            [
                "[experimental]",
                "stack = true",
                "",
                "[experimental.pgdelta]",
                "enabled = true",
                "",
            ]
        )
    (supabase / "config.toml").write_text("\n".join(config), encoding="utf-8")


def usage_snapshot() -> tuple[float, float]:
    self_usage = resource.getrusage(resource.RUSAGE_SELF)
    child_usage = resource.getrusage(resource.RUSAGE_CHILDREN)
    return (
        self_usage.ru_utime + child_usage.ru_utime,
        self_usage.ru_stime + child_usage.ru_stime,
    )


def sample_process_tree(root_pid: int) -> int:
    try:
        listing = subprocess.run(
            ["ps", "-axo", "pid=,ppid=,rss="],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        return 0
    parents: dict[int, int] = {}
    rss: dict[int, int] = {}
    for line in listing.splitlines():
        fields = line.split()
        if len(fields) != 3:
            continue
        try:
            pid, parent, size = (int(field) for field in fields)
        except ValueError:
            continue
        parents[pid] = parent
        rss[pid] = size
    pids = {root_pid}
    changed = True
    while changed:
        changed = False
        for pid, parent in parents.items():
            if parent in pids and pid not in pids:
                pids.add(pid)
                changed = True
    # ps reports RSS in KiB on both macOS and Linux.
    return sum(rss.get(pid, 0) for pid in pids) * 1024


def run_command(
    cli: Path,
    args: list[str],
    project: Path,
    env: dict[str, str],
    records: list[dict[str, Any]],
    label: str,
    *,
    timed: bool = True,
) -> subprocess.CompletedProcess[str]:
    command = [str(cli), *args, "--workdir", str(project)]
    before = usage_snapshot()
    started = time.perf_counter()
    peak_rss = 0
    try:
        with tempfile.TemporaryFile(mode="w+t") as stdout_file, tempfile.TemporaryFile(
            mode="w+t"
        ) as stderr_file:
            process = subprocess.Popen(
                command,
                cwd=project,
                env=env,
                stdout=stdout_file,
                stderr=stderr_file,
                text=True,
                start_new_session=True,
            )
            deadline = started + TIMEOUT_SECONDS
            timed_out = False
            while process.poll() is None:
                peak_rss = max(peak_rss, sample_process_tree(process.pid))
                if time.perf_counter() >= deadline:
                    try:
                        os.killpg(process.pid, signal.SIGKILL)
                    except ProcessLookupError:
                        pass
                    timed_out = True
                    break
                time.sleep(0.25)
            process.wait()
            stdout_file.seek(0)
            stderr_file.seek(0)
            stdout, stderr = stdout_file.read(), stderr_file.read()
            returncode = None if timed_out else process.returncode
    except OSError as error:
        timed_out = False
        stdout, stderr = "", str(error)
        returncode = None
    after = usage_snapshot()
    record = {
        "label": label,
        "command": command,
        "timed": timed,
        "duration_ms": round((time.perf_counter() - started) * 1000, 2) if timed else None,
        "cpu_user_seconds_delta": round(after[0] - before[0], 3),
        "cpu_system_seconds_delta": round(after[1] - before[1], 3),
        "process_tree_peak_rss_bytes_sampled": peak_rss,
        "returncode": returncode,
        "timed_out": timed_out,
        "stdout": stdout,
        "stderr": stderr,
    }
    records.append(record)
    if returncode != 0:
        raise RuntimeError(f"{label} failed (exit {returncode}, timeout={timed_out})")
    return subprocess.CompletedProcess(command, returncode, stdout, stderr)


def base_args(implementation: str, runtime: str) -> list[str]:
    if implementation == "new":
        return ["--experimental"]
    return []


def stack_start_args(implementation: str, runtime: str) -> list[str]:
    if implementation == "new":
        return [
            *base_args(implementation, runtime),
            "start",
            "--runtime",
            runtime,
            "--exclude",
            "rest,auth,realtime,storage,functions,studio,mail,analytics,pooler",
            "--output-format",
            "json",
        ]
    if runtime != "docker":
        raise ValueError("the released legacy CLI has no native runtime")
    return [
        "start",
        "--exclude",
        "gotrue,realtime,storage-api,imgproxy,kong,mailpit,postgrest,postgres-meta,studio,edge-runtime,logflare,vector,supavisor",
    ]


def migration_files(project: Path) -> set[str]:
    folder = project / "supabase" / "migrations"
    return {path.name for path in folder.glob("*.sql")}


def command_for_diff(
    implementation: str,
    scenario: str,
    *,
    apply: bool,
    no_cache: bool = False,
) -> list[str]:
    if implementation == "new":
        args = [*base_args(implementation, "native"), "db", "schema", "declarative", "sync"]
        args.extend(["--name", scenario.replace("_", "-")])
        args.append("--apply" if apply else "--no-apply")
        if no_cache:
            args.append("--no-cache")
        return args
    return ["db", "diff", "--local", "-f", scenario.replace("_", "-")]


def run_diff_cycle(
    cli: Path,
    implementation: str,
    runtime: str,
    project: Path,
    env: dict[str, str],
    records: list[dict[str, Any]],
    artifact_root: Path,
    scenario: str,
) -> None:
    before = migration_files(project)
    if implementation == "new":
        run_command(
            cli,
            command_for_diff(implementation, scenario, apply=True),
            project,
            env,
            records,
            f"{scenario}.generate-and-apply",
        )
    else:
        run_command(
            cli,
            command_for_diff(implementation, scenario, apply=False),
            project,
            env,
            records,
            f"{scenario}.generate",
        )
        created = migration_files(project) - before
        if created:
            run_command(
                cli,
                ["migration", "up", "--local"],
                project,
                env,
                records,
                f"{scenario}.apply",
            )
    after = migration_files(project)
    if after == before:
        raise RuntimeError(f"{scenario} changed the declarative schema but wrote no migration")
    snapshot_migrations(project, artifact_root, scenario, after - before, records)

    assertion_sql = {
        "add_table": "SELECT to_regclass('public.bench_added') IS NOT NULL;",
        "add_column": "SELECT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='bench_items' AND column_name='created_at');",
        "view_function": "SELECT to_regclass('public.bench_items_view') IS NOT NULL AND to_regprocedure('public.bench_item_count()') IS NOT NULL;",
        "related_index_fk_rls": "SELECT to_regclass('public.bench_orders') IS NOT NULL AND to_regclass('public.bench_orders_item_id_idx') IS NOT NULL AND EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.bench_orders'::regclass AND confrelid='public.bench_items'::regclass AND contype='f') AND EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='bench_orders' AND policyname='bench_orders_read');",
        "large_schema_small_edit": "SELECT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='bench_items' AND column_name='large_schema_probe');",
    }
    assert_sql(
        project,
        env,
        records,
        f"{scenario}.catalog-verification",
        assertion_sql[scenario],
    )

    if implementation == "new":
        args = [*base_args(implementation, runtime), "db", "schema", "declarative", "sync", "--no-apply"]
        label = f"{scenario}.convergence-check"
    else:
        args = ["db", "diff", "--local"]
        label = f"{scenario}.convergence-check"
    result = run_command(cli, args, project, env, records, label, timed=False)
    if "No schema changes found" not in result.stderr + result.stdout:
        raise RuntimeError(f"{scenario} did not converge to an empty diff")


def run_profile(
    cli: Path,
    implementation: str,
    runtime: str,
    root: Path,
    artifact_root: Path,
    profile: str,
    table_count: int,
    records: list[dict[str, Any]],
) -> None:
    project = root / profile
    project.mkdir(parents=True)
    create_project(project, implementation, table_count)
    env = os.environ.copy()
    env.update(
        {
            "SUPABASE_HOME": str(root / "home"),
            "SUPABASE_NO_UPDATE_NOTIFIER": "1",
            "SUPABASE_TELEMETRY_DISABLED": "1",
            "SUPABASE_YES": "1",
            "PGPASSWORD": "postgres",
        }
    )
    if implementation == "new":
        env["SUPABASE_EXPERIMENTAL_STACK"] = "1"
    else:
        env.pop("SUPABASE_EXPERIMENTAL_STACK", None)
    started = False
    try:
        # Keep setup database-only: these workflows consume PostgreSQL, and service startup is a
        # separate benchmark. Image/artifact preparation is outside all measured commands.
        run_command(cli, stack_start_args(implementation, runtime), project, env, records, f"{profile}.setup.start", timed=False)
        started = True
        run_command(cli, [*base_args(implementation, runtime), "db", "reset", "--local", "--no-seed"], project, env, records, f"{profile}.setup.baseline-reset", timed=False)
        version = assert_sql(
            project,
            env,
            records,
            f"{profile}.metadata.postgres-version",
            "SELECT version();",
            expected="",
        )
        if not version:
            raise RuntimeError("PostgreSQL version query returned no value")
        if table_count:
            assert_sql(
                project,
                env,
                records,
                f"{profile}.fixture.table-count",
                "SELECT count(*) = 100 FROM pg_tables WHERE schemaname='public' AND tablename ~ '^bench_[0-9]{3}$';",
            )

        diff_args = command_for_diff(implementation, "no-change", apply=False)
        for label in ("first", "repeat"):
            before = migration_files(project)
            no_change = run_command(cli, diff_args, project, env, records, f"{profile}.declarative.no-change.{label}")
            if migration_files(project) != before or "No schema changes found" not in no_change.stdout + no_change.stderr:
                raise RuntimeError("no-change declarative diff unexpectedly produced a migration")
        if implementation == "new":
            before = migration_files(project)
            no_cache = run_command(
                cli,
                command_for_diff(implementation, "no-change", apply=False, no_cache=True),
                project,
                env,
                records,
                f"{profile}.declarative.no-change.no-cache",
            )
            if "No schema changes found" not in no_cache.stdout + no_cache.stderr:
                raise RuntimeError("no-cache declarative diff unexpectedly reported changes")
            if migration_files(project) != before:
                raise RuntimeError("no-cache declarative diff unexpectedly wrote a migration")

        # Benchmark ordinary `db diff` separately from declarative sync. With the schema tree
        # moved aside it compares the migration baseline directly to the live local database.
        schemas_dir = project / "supabase" / "schemas"
        hidden_schemas = project / "supabase" / ".bench-schemas"
        schemas_dir.rename(hidden_schemas)
        try:
            for label in ("first", "repeat"):
                no_change = run_command(
                    cli,
                    ["db", "diff", "--local"],
                    project,
                    env,
                    records,
                    f"{profile}.db-diff.no-change.{label}",
                )
                if "No schema changes found" not in no_change.stdout + no_change.stderr:
                    raise RuntimeError("no-change db diff reported schema changes")
            psql = shutil.which("psql")
            if psql is None:
                raise RuntimeError("psql is required for direct db diff mutation and seed checks")
            direct_sql = "ALTER TABLE public.bench_items ADD COLUMN db_diff_probe integer;"
            psql_command = [psql, "-h", "127.0.0.1", "-p", "54322", "-U", "postgres", "-d", "postgres", "-w"]
            psql_record = run_external(
                [*psql_command, "-v", "ON_ERROR_STOP=1", "-c", direct_sql],
                project,
                env,
                records,
                f"{profile}.db-diff.mutate-setup",
            )
            if psql_record.returncode != 0:
                raise RuntimeError("failed to create direct db diff probe column")
            before = migration_files(project)
            run_command(
                cli,
                ["db", "diff", "--local", "-f", "direct-db-diff"],
                project,
                env,
                records,
                f"{profile}.db-diff.changed",
            )
            if migration_files(project) == before:
                raise RuntimeError("db diff did not write a migration for the live schema change")
            snapshot_migrations(
                project,
                artifact_root,
                f"{profile}-direct-db-diff",
                migration_files(project) - before,
                records,
            )
            run_command(
                cli,
                [*base_args(implementation, runtime), "db", "reset", "--local", "--no-seed"],
                project,
                env,
                records,
                f"{profile}.db-diff.apply-reset",
            )
            applied = run_external(
                [*psql_command, "-At", "-c", "SELECT count(*) FROM information_schema.columns WHERE table_schema='public' AND table_name='bench_items' AND column_name='db_diff_probe';"],
                project,
                env,
                records,
                f"{profile}.db-diff.apply-verification",
            )
            if applied.returncode != 0 or applied.stdout.strip() != "1":
                raise RuntimeError("db diff migration did not apply the live schema change")
            empty_diff = run_command(cli, ["db", "diff", "--local"], project, env, records, f"{profile}.db-diff.convergence", timed=False)
            if "No schema changes found" not in empty_diff.stdout + empty_diff.stderr:
                raise RuntimeError("db diff did not converge to an empty diff after migration up")
        finally:
            hidden_schemas.rename(schemas_dir)

        if profile == "small":
            cases = [
                ("add_table", "\nCREATE TABLE public.bench_added (id bigint PRIMARY KEY, value text NOT NULL);\n"),
                ("add_column", "\nALTER TABLE public.bench_items ADD COLUMN created_at timestamptz NOT NULL DEFAULT now();\n"),
                (
                    "view_function",
                    """
CREATE VIEW public.bench_items_view AS SELECT id, payload FROM public.bench_items;
CREATE FUNCTION public.bench_item_count() RETURNS bigint LANGUAGE sql STABLE AS $$ SELECT count(*) FROM public.bench_items $$;
""",
                ),
                (
                    "related_index_fk_rls",
                    """
CREATE TABLE public.bench_orders (id bigint PRIMARY KEY, item_id bigint NOT NULL REFERENCES public.bench_items(id), amount integer NOT NULL);
CREATE INDEX bench_orders_item_id_idx ON public.bench_orders(item_id);
ALTER TABLE public.bench_orders ENABLE ROW LEVEL SECURITY;
CREATE POLICY bench_orders_read ON public.bench_orders FOR SELECT TO anon USING (true);
""",
                ),
            ]
            current = baseline_sql(table_count) + "\nALTER TABLE public.bench_items ADD COLUMN db_diff_probe integer;\n"
            for name, addition in cases:
                current += addition
                write_schema(project, current)
                run_diff_cycle(cli, implementation, runtime, project, env, records, artifact_root, name)
        else:
            current = baseline_sql(table_count) + "\nALTER TABLE public.bench_items ADD COLUMN db_diff_probe integer;\n"
            current += "\nALTER TABLE public.bench_items ADD COLUMN large_schema_probe text;\n"
            write_schema(project, current)
            run_diff_cycle(cli, implementation, runtime, project, env, records, artifact_root, "large_schema_small_edit")

        # Exercise db reset with seeds separately, then query the database to prove seed.sql ran.
        run_command(
            cli,
            [*base_args(implementation, runtime), "db", "reset", "--local"],
            project,
            env,
            records,
            f"{profile}.reset-with-seed",
        )
        seeded = run_external(
            [shutil.which("psql") or "psql", "-h", "127.0.0.1", "-p", "54322", "-U", "postgres", "-d", "postgres", "-w", "-At", "-c", "SELECT count(*) FROM public.bench_items WHERE payload = 'seeded';"],
            project,
            env,
            records,
            f"{profile}.seed-verification",
        )
        if seeded.returncode != 0 or seeded.stdout.strip() != "1":
            raise RuntimeError(f"db reset did not insert exactly one seed row: {seeded.stdout.strip()}")
    finally:
        cleanup_args = (
            [*base_args(implementation, runtime), "stack", "destroy", "--yes"]
            if implementation == "new"
            else ["stop", "--no-backup"]
        )
        try:
            run_command(cli, cleanup_args, project, env, records, f"{profile}.cleanup", timed=False)
        except Exception:
            if started:
                raise
    # Keep only the JSON results and command diagnostics under the upload directory.
    shutil.rmtree(project)


def run_external(
    command: list[str],
    project: Path,
    env: dict[str, str],
    records: list[dict[str, Any]],
    label: str,
) -> subprocess.CompletedProcess[str]:
    before = usage_snapshot()
    result = subprocess.run(command, cwd=project, env=env, capture_output=True, text=True, check=False)
    after = usage_snapshot()
    records.append(
        {
            "label": label,
            "command": command,
            "timed": False,
            "duration_ms": None,
            "cpu_user_seconds_delta": round(after[0] - before[0], 3),
            "cpu_system_seconds_delta": round(after[1] - before[1], 3),
            "process_tree_peak_rss_bytes_sampled": None,
            "returncode": result.returncode,
            "timed_out": False,
            "stdout": result.stdout,
            "stderr": result.stderr,
        }
    )
    return result


def assert_sql(
    project: Path,
    env: dict[str, str],
    records: list[dict[str, Any]],
    label: str,
    sql: str,
    *,
    expected: str = "t",
) -> str:
    psql = shutil.which("psql")
    if psql is None:
        raise RuntimeError("psql must be installed on the CI runner")
    command = [
        psql,
        "-h",
        "127.0.0.1",
        "-p",
        "54322",
        "-U",
        "postgres",
        "-d",
        "postgres",
        "-w",
        "-At",
        "-c",
        sql,
    ]
    result = run_external(command, project, env, records, label)
    value = result.stdout.strip()
    if result.returncode != 0 or (expected and value != expected):
        raise RuntimeError(f"{label} failed: expected {expected!r}, got {value!r}")
    return value


def snapshot_migrations(
    project: Path,
    artifact_root: Path,
    label: str,
    filenames: set[str],
    records: list[dict[str, Any]],
) -> None:
    snapshots = artifact_root / "migration-snapshots" / label
    snapshots.mkdir(parents=True, exist_ok=True)
    copied: list[dict[str, str]] = []
    migrations_dir = project / "supabase" / "migrations"
    for filename in sorted(filenames):
        sql = (migrations_dir / filename).read_text(encoding="utf-8")
        destination = snapshots / filename
        destination.write_text(sql, encoding="utf-8")
        copied.append({"path": str(destination.relative_to(artifact_root)), "sql": sql})
    records.append(
        {
            "label": f"{label}.migration-snapshots",
            "timed": False,
            "files": copied,
        }
    )


def main() -> int:
    args = parse_args()
    cli = args.cli.resolve()
    if not cli.is_file():
        raise FileNotFoundError(f"CLI executable does not exist: {cli}")
    if args.implementation == "legacy" and args.runtime == "native":
        raise ValueError("legacy CLI supports Docker only; run legacy samples with --runtime docker")
    sample_id = f"{args.sample}-{uuid.uuid4().hex[:10]}"
    root = args.output.resolve() / args.implementation / args.runtime / sample_id
    root.mkdir(parents=True, exist_ok=False)
    scratch_parent = Path(os.environ.get("RUNNER_TEMP", tempfile.gettempdir()))
    scratch_parent.mkdir(parents=True, exist_ok=True)
    scratch = Path(tempfile.mkdtemp(prefix=f"schema-{sample_id}-", dir=scratch_parent))
    (scratch / "home").mkdir()
    records: list[dict[str, Any]] = []
    report: dict[str, Any] = {
        "schema": 1,
        "sample": args.sample,
        "sample_id": sample_id,
        "implementation": args.implementation,
        "runtime": args.runtime,
        "cli": str(cli),
        "cli_version": None,
        "platform": platform.platform(),
        "architecture": platform.machine(),
        "timing_scope": "schema/diff commands only; stack startup and baseline reset are setup",
        "memory_scope": "sampled CLI process and live descendants every 250 ms; excludes container daemons and may miss short-lived peaks",
        "cpu_scope": "resource usage deltas include CLI and waited children, plus the lightweight ps sampler",
        "engine_comparison": "new declarative workflow uses pg-delta sync; legacy uses default db diff with declarative SQL files; direct db diff is measured separately with each CLI default",
        "records": records,
        "status": "running",
    }
    result_file = root / "schema-sample.json"
    try:
        if shutil.which("psql") is None:
            raise RuntimeError("psql must be installed on the CI runner")
        version = run_command(cli, ["--version"], root, os.environ.copy(), records, "metadata.version", timed=False)
        report["cli_version"] = version.stdout.strip()
        for profile, table_count in (("small", 0), ("large", 100)):
            run_profile(
                cli,
                args.implementation,
                args.runtime,
                scratch,
                root,
                profile,
                table_count,
                records,
            )
        report["status"] = "success"
    except Exception as error:  # Preserve raw command output and the failure in the sample artifact.
        report["status"] = "failed"
        report["error"] = f"{type(error).__name__}: {error}"
        report["failed_command"] = records[-1] if records else None
    finally:
        report["finished_at_unix"] = time.time()
        result_file.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        shutil.rmtree(scratch, ignore_errors=True)
    print(json.dumps({"status": report["status"], "result": str(result_file)}, indent=2))
    return 0 if report["status"] == "success" else 1


if __name__ == "__main__":
    raise SystemExit(main())
