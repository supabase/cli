import { existsSync } from "node:fs";
import { BunServices } from "@effect/platform-bun";
import { describe, expect, it } from "@effect/vitest";
import { ConfigProvider, Effect, Exit, FileSystem, Layer, Path } from "effect";

import { mockCommandSettings, useTempWorkdir } from "../../../tests/helpers/command-mocks.ts";
import { mockOutput } from "../../../tests/helpers/mocks.ts";
import { sparkHttp } from "./spark-backend.ts";
import {
  sparkDbDiff,
  sparkDbPush,
  sparkStart,
  sparkStop,
  sparkUnsupported,
  withSparkBackend,
} from "./spark-commands.ts";

const workdir = useTempWorkdir("supabase-spark-int-");

const sparkBin = process.env["SUPABASE_SPARK_BIN"] ?? "";
const pgDeltaDir = process.env["SUPABASE_PG_DELTA_DIR"] ?? "";
const hasSpark = sparkBin !== "" && existsSync(sparkBin);
const hasPgDelta = pgDeltaDir !== "" && existsSync(`${pgDeltaDir}/src/cli/main.ts`);

const basePort = 56000 + (process.pid % 400) * 4;
const ports = { api: basePort, spark: basePort + 1 };

const layers = (output: ReturnType<typeof mockOutput>) =>
  Layer.mergeAll(
    BunServices.layer,
    output.layer,
    mockCommandSettings({ workdir: workdir.current }),
    ConfigProvider.layerAdd(
      ConfigProvider.fromEnvRecord({
        SUPABASE_SPARK_BIN: sparkBin,
        SUPABASE_PG_DELTA_DIR: pgDeltaDir,
        SUPABASE_SPARK_NO_STUDIO: "true",
        SUPABASE_SPARK_API_PORT: String(ports.api),
        SUPABASE_SPARK_PORT: String(ports.spark),
      }),
      { asPrimary: true },
    ),
  );

const writeProject = Effect.fn(function* (migrations: Record<string, string>) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const supabase = path.join(workdir.current, "supabase");
  yield* fs.makeDirectory(path.join(supabase, "migrations"), { recursive: true });
  yield* fs.writeFileString(path.join(supabase, "config.toml"), 'project_id = "spark-int"\n');
  for (const [name, sql] of Object.entries(migrations)) {
    yield* fs.writeFileString(path.join(supabase, "migrations", name), sql);
  }
});

const TODOS =
  "create table public.todos (id bigint generated by default as identity primary key, title text not null);\n";

describe("Spark backend switch", () => {
  it.effect("runs the Postgres path for a project that never opted into Spark", () => {
    const output = mockOutput();
    return Effect.gen(function* () {
      yield* writeProject({});
      const ran = yield* withSparkBackend(Effect.succeed("postgres"), Effect.succeed("spark"));
      expect(ran).toBe("postgres");
    }).pipe(Effect.provide(layers(output)));
  });

  it.effect("keeps a project on Spark once it opted in", () => {
    const output = mockOutput();
    return Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem;
      yield* writeProject({});
      yield* fs.makeDirectory(`${workdir.current}/supabase/.spark`, { recursive: true });
      yield* fs.writeFileString(`${workdir.current}/supabase/.spark/backend`, "spark\n");
      const ran = yield* withSparkBackend(Effect.succeed("postgres"), Effect.succeed("spark"));
      expect(ran).toBe("spark");
    }).pipe(Effect.provide(layers(output)));
  });

  it.effect("fails a command Spark does not implement with a clear message", () =>
    Effect.gen(function* () {
      const exit = yield* Effect.exit(sparkUnsupported("db dump"));
      expect(exit).toStrictEqual(
        Exit.fail(
          expect.objectContaining({
            _tag: "SparkUnsupportedError",
            message:
              "`supabase db dump` is not supported on the experimental Spark backend (no Postgres runs locally).",
          }),
        ),
      );
    }),
  );
});

describe.skipIf(!hasSpark)("Spark db push", () => {
  it.live(
    "applies pending migrations after a dry run and reports an up-to-date database next",
    () => {
      const output = mockOutput({ format: "text" });
      return Effect.gen(function* () {
        const fs = yield* FileSystem.FileSystem;
        yield* writeProject({ "20260101000000_todos.sql": TODOS });
        yield* sparkStart();
        yield* fs.writeFileString(
          `${workdir.current}/supabase/migrations/20260102000000_done.sql`,
          "alter table public.todos add column done boolean not null default false;\n",
        );

        yield* sparkDbPush();
        const state = JSON.parse(
          yield* fs.readFileString(`${workdir.current}/supabase/.spark/state.json`),
        );
        const rows = yield* sparkHttp(
          "GET",
          `http://127.0.0.1:${ports.api}/rest/v1/todos?select=done`,
          {
            headers: { apikey: state.keys.service, authorization: `Bearer ${state.keys.service}` },
          },
        );
        yield* sparkDbPush();

        expect(rows.status).toBe(200);
        expect(output.stderrText).toContain("Applying migration 20260102000000_done.sql...");
        expect(output.stdoutText).toContain(
          "Finished supabase db push.\nRemote database is up to date.\n",
        );
      }).pipe(Effect.ensuring(sparkStop().pipe(Effect.ignore)), Effect.provide(layers(output)));
    },
    120_000,
  );

  it.live(
    "pushes nothing when one pending migration does not apply on Spark",
    () => {
      const output = mockOutput({ format: "text" });
      return Effect.gen(function* () {
        const fs = yield* FileSystem.FileSystem;
        yield* writeProject({ "20260101000000_todos.sql": TODOS });
        yield* sparkStart();
        yield* fs.writeFileString(
          `${workdir.current}/supabase/migrations/20260102000000_ok.sql`,
          "alter table public.todos add column note text;\n",
        );
        yield* fs.writeFileString(
          `${workdir.current}/supabase/migrations/20260103000000_fn.sql`,
          "create function public.add(a int, b int) returns int language plpgsql as $$ begin return a + b; end $$;\n",
        );

        const exit = yield* Effect.exit(sparkDbPush());

        expect(Exit.isFailure(exit)).toBe(true);
        expect(output.stderrText).toContain("20260103000000_fn.sql:1:");
        expect(output.stderrText).not.toContain("Applying migration");
      }).pipe(Effect.ensuring(sparkStop().pipe(Effect.ignore)), Effect.provide(layers(output)));
    },
    120_000,
  );
});

describe.skipIf(!hasSpark || !hasPgDelta)("Spark db diff", () => {
  it.live(
    "writes a proven migration for an edited schema file",
    () => {
      const output = mockOutput({ format: "text" });
      return Effect.gen(function* () {
        const fs = yield* FileSystem.FileSystem;
        yield* writeProject({ "20260101000000_todos.sql": TODOS });
        yield* sparkStart();
        yield* fs.makeDirectory(`${workdir.current}/supabase/schemas`, { recursive: true });
        yield* fs.writeFileString(
          `${workdir.current}/supabase/schemas/todos.sql`,
          `${TODOS}create table public.tags (id bigint generated by default as identity primary key, name text not null);\n`,
        );

        yield* sparkDbDiff("add_tags");

        const files = yield* fs.readDirectory(`${workdir.current}/supabase/migrations`);
        const created = files.find((f) => f.endsWith("_add_tags.sql"));
        expect(created).toBeDefined();
        expect(
          yield* fs.readFileString(`${workdir.current}/supabase/migrations/${created}`),
        ).toContain("tags");
        expect(output.stderrText).toContain("Proof: OK");
      }).pipe(Effect.ensuring(sparkStop().pipe(Effect.ignore)), Effect.provide(layers(output)));
    },
    120_000,
  );
});
