import type { BreakingChange } from "./define.ts";

/** `breaking_changes` entry of a `clispec 002` command. */
export interface DocsBreakingChange {
  readonly id: string;
  readonly major: number;
  readonly summary: string;
  /** `upcoming` on a major before the change, `changed` on the major that ships it. */
  readonly direction: "upcoming" | "changed";
  readonly flags?: ReadonlyArray<string>;
  readonly migration_url: string;
}

const GUIDE_PATH = "/docs/reference/cli/v3/migrating-from-v2";

/** The entries for `commandId` (a dash-joined path such as `supabase-db-push`) in a spec for `specMajor`. */
export function docsBreakingChangesFor(
  registry: ReadonlyArray<BreakingChange>,
  commandId: string,
  specMajor: number,
): ReadonlyArray<DocsBreakingChange> {
  return registry.flatMap((change) => {
    if (!change.commands.some((command) => commandIdOf(command) === commandId)) return [];
    const direction = specMajor >= change.major ? "changed" : "upcoming";
    if (direction === "upcoming" && change.warnInPrevious !== true) return [];
    return [
      {
        id: change.id,
        major: change.major,
        summary: change.summary,
        direction,
        ...(change.flags === undefined ? {} : { flags: change.flags }),
        migration_url: `${GUIDE_PATH}#${change.id}`,
      },
    ];
  });
}

/** Command ids named by a registry entry, for validating it against the walked tree. */
export function commandIdOf(command: string): string {
  return ["supabase", ...command.split(" ")].join("-");
}

const code = (values: ReadonlyArray<string>): string =>
  values.map((value) => `\`${value}\``).join(", ");

/**
 * The migration guide page: changes grouped by theme, then an index by command. Anchors are the
 * change ids that `migration_url` links to.
 */
export function migrationGuideMdx(registry: ReadonlyArray<BreakingChange>): string {
  const themes = [...new Set(registry.map((change) => change.theme))];
  const body = themes.map((theme) => {
    const entries = registry
      .filter((change) => change.theme === theme)
      .map((change) => {
        const affects = [
          `**Commands:** ${code(change.commands.map((command) => `supabase ${command}`))}`,
          ...(change.flags === undefined ? [] : [`**Flags:** ${code(change.flags)}`]),
          ...(change.renamedFrom === undefined
            ? []
            : [
                `**Renamed:** ${code([`supabase ${change.renamedFrom.command}`])} is now ${code([change.renamedFrom.to])}`,
              ]),
        ];
        return [
          `<span id="${change.id}" />`,
          "",
          `### ${change.summary}`,
          "",
          affects.join("\n\n"),
          "",
          change.migration.trim(),
        ].join("\n");
      });
    return [`## ${theme}`, "", entries.join("\n\n")].join("\n");
  });

  const commands = [...new Set(registry.flatMap((change) => change.commands))].toSorted();
  const index = commands.map((command) => {
    const links = registry
      .filter((change) => change.commands.includes(command))
      .map((change) => `[${change.id}](#${change.id})`);
    return `- \`supabase ${command}\`: ${links.join(", ")}`;
  });

  return [
    "---",
    "title: Migrating from v2",
    "subtitle: 'Breaking changes between Supabase CLI v2 and v3.'",
    "description: 'Breaking changes between Supabase CLI v2 and v3.'",
    "---",
    "",
    "{/* Generated by apps/cli/scripts/publish-docs-spec.ts in supabase/cli. Do not edit; change apps/cli/src/docs/breaking-changes there. */}",
    "",
    "Supabase CLI v3 changes some defaults and flags. Each change below lists what is affected and how to update.",
    "",
    body.join("\n\n"),
    "",
    "## Index by command",
    "",
    index.join("\n"),
    "",
  ].join("\n");
}
