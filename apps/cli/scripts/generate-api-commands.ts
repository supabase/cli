import { BunRuntime, BunServices } from "@effect/platform-bun";
import { Console, Data, Effect, FileSystem, Path, Predicate, Schema, Stream } from "effect";
import { ChildProcess, ChildProcessSpawner } from "effect/process";
import { rootCommandForFeatures } from "../src/cli/root.ts";
import {
  generatedOperations,
  nouns,
  commandPolicies,
} from "../src/commands/api/api-command-policy.ts";
import { openApiOperationIdMap } from "@supabase/api/effect";
import { renderApiCommandReference } from "./api-command-reference.ts";
import { ApiCommandGenerationError, deriveApiCommands } from "./api-command-derive.ts";

class ApiCommandFormatError extends Data.TaggedError("ApiCommandFormatError")<{
  readonly message: string;
}> {}

class ApiCommandDriftError extends Data.TaggedError("ApiCommandDriftError")<{
  readonly files: ReadonlyArray<string>;
}> {
  override get message(): string {
    return `Generated API command files are out of date: ${this.files.join(", ")}. Run \`pnpm --filter supabase run api-commands:generate\`.`;
  }
}

const HEADER = "// Generated by scripts/generate-api-commands.ts. Do not edit.\n";
const encodeJson = Schema.encodeEffect(Schema.fromJsonString(Schema.Unknown, { space: 2 }));
const decodeJson = Schema.decodeUnknownEffect(Schema.fromJsonString(Schema.Unknown));
const ROOT_OPTIONS: ReadonlyArray<Parameters<typeof rootCommandForFeatures>[0]> = [
  { stackBackend: "legacy", computeEnabled: false },
  { stackBackend: "legacy", computeEnabled: true },
  { stackBackend: "stack", computeEnabled: false },
  { stackBackend: "stack", computeEnabled: true },
];

/** The root command names: the union of the trees every backend and feature option builds. */
const handWrittenRoots = Effect.fn("ApiCommands.collectHandWrittenRoots")(function* () {
  const roots = new Set<string>();
  for (const options of ROOT_OPTIONS) {
    for (const { commands } of rootCommandForFeatures(options).subcommands) {
      for (const command of commands) roots.add(command.name);
    }
  }
  yield* Effect.annotateCurrentSpan({ "handWritten.roots": roots.size });
  return roots;
});

/** Formats in memory with the repo's oxfmt config so the committed files match `pnpm fmt`. */
const format = Effect.fn("ApiCommands.format")(function* (
  repoRoot: string,
  filePath: string,
  source: string,
) {
  const spawner = yield* ChildProcessSpawner.ChildProcessSpawner;
  const output = yield* spawner
    .string(
      ChildProcess.make(
        "node_modules/.bin/oxfmt",
        ["-c", ".oxfmtrc.json", "--stdin-filepath", filePath],
        {
          cwd: repoRoot,
          stdin: Stream.make(new TextEncoder().encode(source)),
          stderr: "inherit",
        },
      ),
    )
    .pipe(
      Effect.mapError(
        (error) => new ApiCommandFormatError({ message: `oxfmt failed: ${error.message}` }),
      ),
    );
  if (output.trim() === "") {
    return yield* new ApiCommandFormatError({
      message: `oxfmt produced no output for ${filePath}`,
    });
  }
  return output;
});

const main = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const check = process.argv.includes("--check");
  const cliRoot = path.resolve(import.meta.dir, "..");
  const repoRoot = path.resolve(cliRoot, "../..");
  const specPath = path.join(repoRoot, "packages/api/src/generated/openapi.json");
  const spec = yield* decodeJson(yield* fs.readFileString(specPath));
  if (!Predicate.isReadonlyObject(spec)) {
    return yield* new ApiCommandGenerationError({ problems: ["openapi.json is not an object"] });
  }

  const { entries, pollTargets, successStatuses, problems } = deriveApiCommands({
    spec,
    generated: generatedOperations,
    policies: commandPolicies,
    nouns,
    operationIdMap: openApiOperationIdMap,
    handWrittenRoots: yield* handWrittenRoots(),
  });
  if (problems.length > 0) return yield* new ApiCommandGenerationError({ problems });

  const outputs = [
    {
      relative: "src/commands/api/generated.ts",
      source: `${HEADER}import type { ApiCommandEntry, ApiPollTarget } from "./api-command.model.ts";\n\nexport const apiCommands = ${yield* encodeJson(entries)} as const satisfies readonly ApiCommandEntry[];\n\nexport const apiPollTargets = ${yield* encodeJson(pollTargets)} as const satisfies readonly ApiPollTarget[];\n`,
    },
    {
      relative: "src/commands/api/generated.md",
      source: renderApiCommandReference({ entries, pollTargets, successStatuses }),
    },
  ];

  const stale: Array<string> = [];
  for (const output of outputs) {
    const target = path.join(cliRoot, output.relative);
    const formatted = yield* format(repoRoot, path.relative(repoRoot, target), output.source);
    if (check) {
      const current = (yield* fs.exists(target)) ? yield* fs.readFileString(target) : undefined;
      if (current !== formatted) stale.push(output.relative);
    } else {
      yield* fs.makeDirectory(path.dirname(target), { recursive: true });
      yield* fs.writeFileString(target, formatted);
      yield* Console.log(`Generated: ${output.relative}`);
    }
  }
  if (stale.length > 0) return yield* new ApiCommandDriftError({ files: stale });
  if (check) yield* Console.log("Generated API command files are up to date.");
  yield* Effect.annotateCurrentSpan({
    "apiCommands.count": entries.length,
    "apiPollTargets.count": pollTargets.length,
  });
});

if (import.meta.main) {
  BunRuntime.runMain(
    main.pipe(Effect.withSpan("ApiCommands.generate"), Effect.provide(BunServices.layer)),
  );
}
