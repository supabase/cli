import { fileURLToPath } from "node:url";
import { BunServices, BunRuntime } from "@effect/platform-bun";
import openapi from "@supabase/api/openapi.json";
import { Console, Effect, FileSystem, Schema } from "effect";
import { generateApiCommands } from "./api-command-generator.ts";
import { apiCommandOperationIds } from "./api-command-operations.ts";

const run = Effect.fn("ApiCommands.generate")(function* () {
  const fs = yield* FileSystem.FileSystem;
  const commands = yield* Effect.try(() => generateApiCommands(openapi, apiCommandOperationIds));
  const directory = fileURLToPath(new URL("../src/command-internal/api/", import.meta.url));
  yield* fs.makeDirectory(directory, { recursive: true });
  const json = yield* Schema.encodeEffect(Schema.fromJsonString(Schema.Unknown, { space: 2 }))(
    commands,
  );
  yield* fs.writeFileString(
    `${directory}generated.ts`,
    `// Generated by scripts/generate-api-commands.ts.\nimport type { ApiCommandData } from "./model.ts";\n\nexport const generatedCommands = ${json} as const satisfies ReadonlyArray<ApiCommandData>;\n`,
  );
  yield* fs.writeFileString(`${directory}api-commands.snapshot.json`, `${json}\n`);
  yield* Console.log(`Generated ${commands.length} API command(s).`);
});

if (import.meta.main) run().pipe(Effect.provide(BunServices.layer), BunRuntime.runMain);
